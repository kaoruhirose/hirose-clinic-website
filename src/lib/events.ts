/**
 * 裸足ハイクなどのイベント。/events ページに表示される。
 *
 * ★日程の管理は Googleフォームで行う★
 *   `formDateQuestion` を設定したイベントは、Googleフォームのその質問（例：「参加希望日」）の
 *   選択肢を、そのまま「開催日程」として表示します（1時間ごとに読み直し）。
 *   → 日程を足す・消すときは、Googleフォームの選択肢を直すだけでOK。
 *   開催日が過ぎた日程は、自動で表示から消えます。
 *
 * `dates` は予備の日程です。フォームを読み取れなかったとき（Googleの仕様変更など）だけ使われます。
 * ときどきフォームの選択肢と合わせておくと安心です。
 * 表示する日程が0件のときは「次回の日程は決まり次第お知らせします」と表示されます。
 *
 * ★文章はこのファイルで直す★
 *   時間・集合場所・参加費・持ち物・キャンセル規定などの文章は、下の `fieldworks` の中に書いてあります。
 *   Googleフォームの説明文や自動メールの文面と、内容を揃えておくこと。
 */
export type ClinicEvent = {
  /** 予備の開催日一覧（開催が近い順） 例: "2026年5月18日（日）"。フォームを読めないときだけ使う */
  dates: string[];
  /** イベント名。画面では改行せず1行で表示する（幅が狭いときは文字が少し小さくなる） */
  title: string;
  /** 時間 例: "9:00〜11:00" */
  time: string;
  /** 集合場所 */
  place: string;
  /** 参加費 例: "無料" / "1,000円（当日現金）" */
  fee: string;
  /** 定員 例: "10名（先着順）" */
  capacity: string;
  /** 説明文（1要素＝1段落） */
  description: string[];
  /** 申込用GoogleフォームのURL（「.../viewform」まで）。未設定なら null で「申込フォーム準備中」表示 */
  formUrl: string | null;
  /** 日程を読み取るGoogleフォームの質問文（例: "参加希望日"）。未設定なら `dates` をそのまま使う */
  formDateQuestion?: string;

  // ---- ここから下は任意。書いた項目だけがページに表示される ----
  /** 説明文の前に置く短い一行 */
  lead?: string;
  /** 冒頭に掲げる言葉と、その作者 */
  epigraph?: { text: string; author: string };
  /** 集合場所の地図（GoogleマップのURL） */
  mapUrl?: string;
  /** 当日の流れ（上から順に番号が付く） */
  flow?: { title: string; text: string }[];
  /** こんな方へ */
  audience?: string[];
  /** 安心して参加していただくための約束ごと */
  reassurance?: string[];
  /** 参加費の表。書くと `fee` の一行表示の代わりにこの表を出す */
  feeTable?: { label: string; first: string; repeat: string }[];
  /** お支払い方法の案内（1要素＝1段落） */
  payment?: string[];
  /** 持ち物・服装。note は補足（なくてもよい） */
  belongings?: { item: string; note?: string }[];
  /** 雨天時の対応 */
  weather?: string;
  /** キャンセル規定（上から順に表示） */
  cancellation?: { when: string; fee: string }[];
  /** キャンセル規定の補足 */
  cancellationNote?: string;
  /** 主催者の紹介。closing は結びの言葉（1要素＝1行） */
  host?: { name: string; role: string; credentials: string; bio: string; closing?: string[] };
};


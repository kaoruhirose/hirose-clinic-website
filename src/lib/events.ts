/**
 * 裸足ハイクなどのイベント。/events ページに表示される。
 *
 * ★使い方：新しい開催日は、各イベントの `dates` に1行足すだけ★
 *   → カードの「開催日程」一覧に自動で並びます。
 *     申込ボタンは1つで、参加希望日はGoogleフォームの中で選んでもらいます。
 *
 * ※ Googleフォーム側の「参加希望日」プルダウンにも、同じ日付を追加してください。
 *
 * 開催が終わった日程は手で削除してください（過去日は自動では消えません）。
 * `dates` が空になると「次回の日程は決まり次第お知らせします」と表示されます。
 */
export type ClinicEvent = {
  /** 開催日の一覧（開催が近い順） 例: "2026年5月18日（日）" */
  dates: string[];
  /** イベント名 */
  title: string;
  /** 時間 例: "9:00〜11:00" */
  time: string;
  /** 集合場所 */
  place: string;
  /** 参加費 例: "無料" / "1,000円（当日現金）" */
  fee: string;
  /** 定員 例: "10名（先着順）" */
  capacity: string;
  /** 説明文 */
  description: string;
  /** 申込用GoogleフォームのURL（「.../viewform」まで）。未設定なら null で「申込フォーム準備中」表示 */
  formUrl: string | null;
};


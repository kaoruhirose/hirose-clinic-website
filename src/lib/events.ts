/**
 * 裸足ハイクなどのイベント日程。
 *
 * ★使い方：新しい開催日は、この配列の先頭に1件足すだけ★
 *   → /events ページにカードが自動で表示され、
 *     その日付が埋め込まれた申込ボタン（Googleフォームの事前入力リンク）が
 *     自動生成されます。
 *
 * ※ Googleフォーム側の「参加希望日」プルダウンには、
 *   ここの `date` とまったく同じ文字列の選択肢を用意してください
 *   （文言が一致していないと日付が自動入力されません）。
 *
 * 開催が終わった日程は削除するか、配列の下に残しておいてください
 * （過去日は自動では消えません）。
 */
export type ClinicEvent = {
  /** 開催日（表示＆フォーム事前入力に使用） 例: "2026年5月18日（日）" */
  date: string;
  /** イベント名 */
  title: string;
  /** 時間 例: "9:00〜11:00" */
  time: string;
  /** 集合場所 */
  place: string;
  /** 参加費 例: "無料" / "1,000円（当日現金）" */
  fee: string;
  /** 定員 例: "10名（先着順）" */
  capacity: string;
  /** 説明文 */
  description: string;
};

// ※ 各 date は Googleフォームの「参加希望日」プルダウンの選択肢と
//    完全一致させること（文言が違うと日付が自動入力されません）。
//    開催が近い順に並べてください。過ぎた日程は削除を。

/**
 * 裸足ハイクなどのイベント。/events ページに表示される。
 *
 * ★日程の管理は Googleフォームで行う★
 *   `formDateQuestion` を設定したイベントは、Googleフォームのその質問（例：「参加希望日」）の
 *   選択肢を、そのまま「開催日程」として表示します（1時間ごとに読み直し）。
 *   → 日程を足す・消すときは、Googleフォームの選択肢を直すだけでOK。
 *   開催日が過ぎた日程は、自動で表示から消えます。
 *
 * `dates` は予備の日程です。フォームを読み取れなかったとき（Googleの仕様変更など）だけ使われます。
 * ときどきフォームの選択肢と合わせておくと安心です。
 * 表示する日程が0件のときは「次回の日程は決まり次第お知らせします」と表示されます。
 */
export type ClinicEvent = {
  /** 予備の開催日一覧（開催が近い順） 例: "2026年5月18日（日）"。フォームを読めないときだけ使う */
  dates: string[];
  /** イベント名 */
  title: string;
  /** 時間 例: "9:00〜11:00" */
  time: string;
  /** 集合場所 */
  place: string;
  /** 参加費 例: "無料" / "1,000円（当日現金）" */
  fee: string;
  /** 定員 例: "10名（先着順）" */
  capacity: string;
  /** 説明文 */
  description: string;
  /** 申込用GoogleフォームのURL（「.../viewform」まで）。未設定なら null で「申込フォーム準備中」表示 */
  formUrl: string | null;
  /** 日程を読み取るGoogleフォームの質問文（例: "参加希望日"）。未設定なら `dates` をそのまま使う */
  formDateQuestion?: string;
};

